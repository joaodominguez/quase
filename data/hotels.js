export function getHotel(slug) {
  return hotels.find((hotel) => hotel.slug === slug);
}

export function hotelsByHub(hub) {
  return hotels.filter((hotel) => hotel.hub === hub);
}

export function getFeaturedHotel() {
  return hotels.find((hotel) => hotel.featured) || hotels[0];
}

export function getLatestReviews(limit = 3, excludeSlug) {
  return hotels.filter((hotel) => hotel.slug !== excludeSlug).slice(0, limit);
}

export function bookingUrl(hotel) {
  return `https://www.booking.com/searchresults.pt-pt.html?ss=${encodeURIComponent(hotel.bookingQuery)}`;
}
